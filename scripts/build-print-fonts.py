"""Builds printing-core/fonts/rich-fonts.mjs: 1-bit glyph atlases for the
approved thermal documents, so the bridge and the on-screen preview draw
identical pixels without a font engine.

    python3 scripts/build-print-fonts.py

Fonts (both licences allow embedding and redistribution; see
printing-core/fonts/FONT-LICENSES.txt):
  DejaVu Sans Condensed (regular, bold, bold oblique) - Bitstream Vera licence
  Liberation Serif Bold - SIL Open Font License 1.1
"""
import base64, json, os, sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIRS = ["/usr/share/fonts/truetype/dejavu", "/usr/share/fonts/truetype/liberation"]
FACES = {
    "sans": "DejaVuSansCondensed.ttf",
    "sansBold": "DejaVuSansCondensed-Bold.ttf",
    "sansBoldItalic": "DejaVuSansCondensed-BoldOblique.ttf",
    "serifBold": "LiberationSerif-Bold.ttf",
}
# Every face and pixel size a style in printing-core/rich-render.mjs uses.
SIZES = {
    "sans": [16, 18, 20, 22, 24, 26, 30, 32],
    "sansBold": [16, 18, 20, 22, 24, 26, 28, 30, 32, 36, 38, 40, 46, 58],
    "sansBoldItalic": [20, 26],
    "serifBold": [38, 54],
}
CHARS = [chr(c) for c in range(32, 127)] + ["☎"]


def find(name):
    for d in FONT_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit(f"missing font {name}")


def atlas(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = {}
    for ch in CHARS:
        try:
            box = font.getbbox(ch, anchor="ls")
        except Exception:
            continue
        adv = round(font.getlength(ch) * 16)
        x0, y0, x1, y1 = box
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        bits = b""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            stride = (w + 7) // 8
            out = bytearray(stride * h)
            px = img.load()
            for y in range(h):
                for x in range(w):
                    if px[x, y] >= 112:
                        out[y * stride + (x >> 3)] |= 0x80 >> (x & 7)
            bits = bytes(out)
        glyphs[str(ord(ch))] = [adv, x0, y0, w, h, base64.b64encode(bits).decode()]
    return {"ascent": ascent, "descent": descent, "glyphs": glyphs}


data = {}
for face, file in FACES.items():
    path = find(file)
    for size in SIZES[face]:
        data[f"{face}/{size}"] = atlas(path, size)

out = os.path.join(os.path.dirname(__file__), "..", "printing-core", "fonts", "rich-fonts.mjs")
with open(out, "w") as f:
    f.write("// Generated by scripts/build-print-fonts.py. Do not edit.\n")
    f.write("// Glyph: [advance x16, x offset, y offset from baseline, width, height, 1-bit rows base64]\n")
    f.write("export const RICH_FONTS = ")
    json.dump(data, f, separators=(",", ":"))
    f.write(";\n")
print(out, os.path.getsize(out))
